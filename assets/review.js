/* Flashcard review with spaced repetition (review/index.html).  security-reviewed:storage

   The cards come from assets/cards-data.js (window.BM_CARDS, generated by build.ps1 from the
   lessons' review questions and summaries). Each card is shown, the learner reveals the answer
   and says whether they remembered it; remembered cards come back after 1, 3, 7, 14 and 30 days
   (Leitner boxes 1-5), forgotten ones go back to box 0 and return tomorrow.

   Storage (study preference only, as the site's security rules allow):
   - one localStorage key holding, per card id, its box number and the day it is next due;
   - nothing else: no text, no names, nothing is sent anywhere;
   - everything read back is treated as untrusted and validated (8-hex ids, small integers), is
     never used as HTML, a URL or a class name, and every storage access is in try/catch.
   If storage is unavailable (private window, blocked) the review still works for the session, it
   just remembers nothing. The page text is only ever set with textContent, never built from HTML,
   and the only link built from card data (back to the lesson) is checked against a strict pattern. */
(function () {
  'use strict';

  var KEY = 'bm.review.v1';
  var ID_RE = /^[0-9a-f]{8}$/;
  var PATH_RE = /^[a-z0-9\/-]+\.html$/;
  var ANCHOR_RE = /^sec-[0-9]+$/;
  var INTERVALS = [0, 1, 3, 7, 14, 30];     // days until the card is due again, by box
  var MAX_BOX = INTERVALS.length - 1;
  var SESSION_SIZE = 20;
  var MAX_DAY = 100000;
  var DIGITS = '٠١٢٣٤٥٦٧٨٩';

  function $(id) { return document.getElementById(id); }

  function arabic(n) {
    return String(n).replace(/[0-9]/g, function (d) { return DIGITS.charAt(Number(d)); });
  }

  // ---- the deck ------------------------------------------------------------------
  var deck = window.BM_CARDS;
  var setup = $('rv-setup');
  if (!deck || !Array.isArray(deck.courses) || !setup) { return; }

  var cards = [];          // every card with its course and lesson
  var byId = {};
  var courses = [];
  deck.courses.forEach(function (course) {
    if (!course || typeof course.id !== 'string' || typeof course.name !== 'string' || !Array.isArray(course.lessons)) { return; }
    var entry = { id: course.id, name: course.name, lessons: [] };
    course.lessons.forEach(function (lesson) {
      if (!lesson || typeof lesson.n !== 'number' || typeof lesson.t !== 'string' || typeof lesson.p !== 'string' ||
          !PATH_RE.test(lesson.p) || !Array.isArray(lesson.c)) { return; }
      entry.lessons.push({ n: lesson.n, t: lesson.t });
      lesson.c.forEach(function (c) {
        if (!c || !ID_RE.test(c.i) || typeof c.f !== 'string' || typeof c.b !== 'string' || byId[c.i]) { return; }
        var card = {
          id: c.i, kind: String(c.k), front: c.f, back: c.b, extra: typeof c.x === 'string' ? c.x : '',
          anchor: ANCHOR_RE.test(c.a) ? c.a : '', path: lesson.p,
          course: course.id, courseName: course.name, n: lesson.n, title: lesson.t
        };
        cards.push(card);
        byId[card.id] = card;
      });
    });
    if (entry.lessons.length) { courses.push(entry); }
  });
  if (cards.length === 0) { return; }

  // ---- storage -------------------------------------------------------------------
  function getStore() {
    try {
      var s = window.localStorage;
      var probe = '__bm_probe__';
      s.setItem(probe, '1');
      s.removeItem(probe);
      return s;
    } catch (e) {
      return null;
    }
  }
  var store = getStore();

  // memory[id] = [box, dueDay]; whatever is in storage may have been edited by anyone
  function clean(raw) {
    var out = {};
    if (!raw || typeof raw !== 'object' || !raw.c || typeof raw.c !== 'object') { return out; }
    Object.keys(raw.c).forEach(function (id) {
      var v = raw.c[id];
      if (!ID_RE.test(id) || !byId[id] || !Array.isArray(v) || v.length !== 2) { return; }
      var box = v[0];
      var due = v[1];
      if (typeof box !== 'number' || box % 1 !== 0 || box < 0 || box > MAX_BOX) { return; }
      if (typeof due !== 'number' || due % 1 !== 0 || due < 0 || due > MAX_DAY) { return; }
      out[id] = [box, due];
    });
    return out;
  }

  function load() {
    if (!store) { return memoryOnly; }
    try {
      var text = store.getItem(KEY);
      return text ? clean(JSON.parse(text)) : {};
    } catch (e) {
      return {};
    }
  }

  var memoryOnly = {};
  function save(memory) {
    if (!store) { memoryOnly = memory; return; }
    try { store.setItem(KEY, JSON.stringify({ v: 1, c: memory })); } catch (e) { /* storage full or blocked: stay silent */ }
  }

  function today() {
    var d = new Date();
    return Math.floor((d.getTime() - d.getTimezoneOffset() * 60000) / 86400000);
  }

  // ---- choosing what to review ---------------------------------------------------
  var selCourse = $('rv-course');
  var selLesson = $('rv-lesson');
  var chkAll = $('rv-all');
  var stats = $('rv-stats');
  var clearBtn = $('rv-clear');

  function option(select, value, label) {
    var o = document.createElement('option');
    o.value = value;
    o.textContent = label;
    select.appendChild(o);
  }

  function fillCourses() {
    option(selCourse, '', 'كل المواد (' + arabic(cards.length) + ' بطاقة)');
    courses.forEach(function (c) {
      var count = cards.filter(function (card) { return card.course === c.id; }).length;
      option(selCourse, c.id, c.name + ' (' + arabic(count) + ')');
    });
  }

  function fillLessons() {
    selLesson.textContent = '';
    option(selLesson, '', 'كل الدروس');
    var picked = courses.filter(function (c) { return c.id === selCourse.value; })[0];
    selLesson.disabled = !picked;
    if (!picked) { return; }
    picked.lessons.forEach(function (l) {
      var count = cards.filter(function (card) { return card.course === picked.id && card.n === l.n; }).length;
      option(selLesson, String(l.n), 'الدرس ' + arabic(l.n) + ': ' + l.t + ' (' + arabic(count) + ')');
    });
  }

  function selection() {
    var course = selCourse.value;
    var lesson = selLesson.value === '' ? 0 : Number(selLesson.value);
    return cards.filter(function (card) {
      return (course === '' || card.course === course) && (lesson === 0 || card.n === lesson);
    });
  }

  function split(list, memory, day) {
    var due = [];
    var fresh = [];
    var later = [];
    list.forEach(function (card) {
      var m = memory[card.id];
      if (!m) { fresh.push(card); } else if (m[1] <= day) { due.push(card); } else { later.push(card); }
    });
    return { due: due, fresh: fresh, later: later };
  }

  function shuffle(list) {
    for (var i = list.length - 1; i > 0; i -= 1) {
      var j = Math.floor(Math.random() * (i + 1));
      var t = list[i]; list[i] = list[j]; list[j] = t;
    }
    return list;
  }

  function showStats() {
    var parts = split(selection(), load(), today());
    var total = parts.due.length + parts.fresh.length + parts.later.length;
    stats.textContent = 'في هذه المجموعة ' + arabic(total) + ' بطاقة: ' + arabic(parts.due.length) + ' حان موعدها، ' +
      arabic(parts.fresh.length) + ' جديدة، ' + arabic(parts.later.length) + ' تأجّل موعدها.';
    clearBtn.hidden = !store || Object.keys(load()).length === 0;
  }

  // ---- a session -----------------------------------------------------------------
  var study = $('rv-study');
  var done = $('rv-done');
  var progress = $('rv-progress');
  var kindLine = $('rv-kind');
  var frontP = $('rv-front');
  var answer = $('rv-answer');
  var backP = $('rv-back');
  var extraP = $('rv-extra');
  var openLink = $('rv-open');
  var showBtn = $('rv-show');
  var yesBtn = $('rv-yes');
  var noBtn = $('rv-no');
  var stopBtn = $('rv-stop');
  var summary = $('rv-summary');
  var againBtn = $('rv-again');

  var queue = [];
  var total = 0;
  var seen = 0;
  var right = 0;
  var wrong = 0;
  var retried = {};          // cards already sent to the end of the queue once
  var current = null;

  var KIND_LABEL = {
    q: 'سؤال مراجعة', o: 'سؤال مراجعة',
    s: 'من خلاصة الدرس: ما الذي ورد عن هذا العنوان؟', z: 'من خلاصة الدرس: أكمل الفراغ'
  };
  var EXTRA_LABEL = { q: 'الشرح: ', z: 'الجملة كاملة: ' };

  function startSession() {
    var day = today();
    var memory = load();
    var parts = split(selection(), memory, day);
    var picked;
    if (chkAll.checked) {
      picked = shuffle(parts.due.concat(parts.fresh, parts.later));
    } else {
      parts.due.sort(function (a, b) { return memory[a.id][1] - memory[b.id][1]; });
      picked = parts.due.concat(shuffle(parts.fresh));
    }
    queue = picked.slice(0, SESSION_SIZE);
    if (queue.length === 0) {
      stats.textContent = 'لا توجد بطاقات مستحقّة الآن في هذه المجموعة. اختر «راجع كل البطاقات» إن أردت المراجعة على أي حال.';
      return;
    }
    total = queue.length;
    seen = 0;
    right = 0;
    wrong = 0;
    retried = {};
    setup.hidden = true;
    done.hidden = true;
    study.hidden = false;
    nextCard();
  }

  function nextCard() {
    current = queue.shift() || null;
    if (!current) { finish(); return; }
    progress.textContent = 'البطاقة ' + arabic(Math.min(seen + 1, total)) + ' من ' + arabic(total);
    kindLine.textContent = (KIND_LABEL[current.kind] || 'بطاقة') + ' · ' + current.courseName + ' · الدرس ' + arabic(current.n);
    frontP.textContent = current.front;
    answer.hidden = true;
    backP.textContent = '';
    extraP.textContent = '';
    showBtn.hidden = false;
    yesBtn.hidden = true;
    noBtn.hidden = true;
    frontP.focus();
  }

  function reveal() {
    if (!current) { return; }
    backP.textContent = current.back;
    extraP.textContent = current.extra ? (EXTRA_LABEL[current.kind] || '') + current.extra : '';
    extraP.hidden = !current.extra;
    if (current.anchor) {
      openLink.href = '../' + current.path + '#' + current.anchor;
      openLink.hidden = false;
    } else {
      openLink.hidden = true;
    }
    answer.hidden = false;
    showBtn.hidden = true;
    yesBtn.hidden = false;
    noBtn.hidden = false;
    yesBtn.focus();
  }

  function rate(remembered) {
    if (!current) { return; }
    var memory = load();
    var day = today();
    var old = memory[current.id];
    if (remembered) {
      if (!retried[current.id]) {              // first try: move up a box (a second try after a miss changes nothing)
        var box = Math.min((old ? old[0] : 0) + 1, MAX_BOX);
        memory[current.id] = [box, day + INTERVALS[box]];
        right += 1;
      }
      seen += 1;
    } else {
      memory[current.id] = [0, day + 1];
      if (!retried[current.id]) {
        wrong += 1;
        retried[current.id] = true;
        queue.push(current);                   // once more at the end of this session
      } else {
        seen += 1;
      }
    }
    save(memory);
    nextCard();
  }

  function finish() {
    study.hidden = true;
    done.hidden = false;
    summary.textContent = 'انتهت الجلسة: تذكّرتَ ' + arabic(right) + ' من ' + arabic(total) + ' بطاقة' +
      (wrong ? '، ونسيتَ ' + arabic(wrong) + ' ستعود إليك غدًا.' : '. أحسنت!') +
      (store ? '' : ' (لم يُحفظ شيء لأن المتصفح يمنع التخزين.)');
    summary.focus();
  }

  function backToSetup() {
    study.hidden = true;
    done.hidden = true;
    setup.hidden = false;
    showStats();
    selCourse.focus();
  }

  // ---- wiring --------------------------------------------------------------------
  var armed = false;
  var armTimer = null;
  function disarm() {
    armed = false;
    clearBtn.textContent = 'مسح بيانات المراجعة';
    if (armTimer) { window.clearTimeout(armTimer); armTimer = null; }
  }

  function init() {
    fillCourses();
    fillLessons();
    setup.hidden = false;
    $('rv-nostore').hidden = !!store;
    showStats();

    selCourse.addEventListener('change', function () { fillLessons(); showStats(); });
    selLesson.addEventListener('change', showStats);
    chkAll.addEventListener('change', showStats);
    setup.addEventListener('submit', function (event) { event.preventDefault(); startSession(); });
    showBtn.addEventListener('click', reveal);
    yesBtn.addEventListener('click', function () { rate(true); });
    noBtn.addEventListener('click', function () { rate(false); });
    stopBtn.addEventListener('click', function () { backToSetup(); });
    againBtn.addEventListener('click', backToSetup);
    clearBtn.addEventListener('click', function () {
      if (!armed) {
        armed = true;
        clearBtn.textContent = 'اضغط مرة أخرى لتأكيد المسح';
        armTimer = window.setTimeout(function () { disarm(); }, 4000);
        return;
      }
      if (store) { try { store.removeItem(KEY); } catch (e) { /* ignore */ } }
      memoryOnly = {};
      disarm();
      showStats();
    });
    disarm();

    window.addEventListener('storage', function (event) {
      if ((event.key === KEY || event.key === null) && !setup.hidden) { showStats(); }
    });
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
})();
